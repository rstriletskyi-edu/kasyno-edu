import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { parseEnv } from 'node:util';
import { format } from 'prettier';

const localFile = new URL('./.env', import.meta.url);
const exampleFile = new URL('./.env.example', import.meta.url);
const values = parseEnv(readFileSync(existsSync(localFile) ? localFile : exampleFile, 'utf8'));
const value = (name) => process.env[name] ?? values[name] ?? '';

// Only these public values are included in the browser bundle.
const config = {
  apiUrl: value('API_URL'),
  firebase: {
    apiKey: value('FIREBASE_API_KEY'),
    authDomain: value('FIREBASE_AUTH_DOMAIN'),
    projectId: value('FIREBASE_PROJECT_ID'),
    appId: value('FIREBASE_APP_ID'),
  },
};

const source = `// Generated by npm run config. Edit frontend/.env instead.
export const environmentConfig = ${JSON.stringify(config)};
`;
writeFileSync(
  new URL('./src/environments/environment.config.ts', import.meta.url),
  await format(source, { parser: 'typescript', singleQuote: true, printWidth: 100 }),
);

if (Object.values(config.firebase).some((entry) => !entry.trim())) {
  console.warn('[config] Firebase settings are incomplete. Fill frontend/.env to enable login.');
}
console.log('[config] Browser configuration generated.');
